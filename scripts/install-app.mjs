// Installs /Applications/FrostCode.app: a copy of this repo's Electron renamed to FrostCode, whose
// app/ folder loads dist/gui/main.js from this checkout. Rebuilding (npm run build) updates the
// app; rerun this script only after an Electron upgrade or if the repo moves.
//   node scripts/install-app.mjs [--dest /Applications] [--save-key]
// --save-key stores this shell's ANTHROPIC_API_KEY in the login Keychain, where the app reads it
// (an app opened from Finder never sees variables exported in a terminal).
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const destDir = process.argv.includes('--dest') ? process.argv[process.argv.indexOf('--dest') + 1] : '/Applications';
const app = join(destDir, 'FrostCode.app');
const BUNDLE_ID = 'com.frostcode.desktop';
const electronApp = join(root, 'node_modules/electron/dist/Electron.app');
const plist = join(app, 'Contents/Info.plist');
const buddy = (cmd, file = plist) => execFileSync('/usr/libexec/PlistBuddy', ['-c', cmd, file], { encoding: 'utf8' }).trim();
const KEYCHAIN_SERVICE = 'FrostCode';

if (process.platform !== 'darwin') throw new Error('The Applications install is macOS only.');

if (process.argv.includes('--save-key')) {
  const key = process.env.ANTHROPIC_API_KEY;
  if (!key) throw new Error('ANTHROPIC_API_KEY is not set in this shell; export it, then run with --save-key again.');
  if (/["\\\n]/.test(key)) throw new Error('That key has characters the Keychain command cannot take.');
  // `security -i` reads the command on stdin, so the key never appears in a process listing.
  execFileSync('/usr/bin/security', ['-i'], {
    input: `add-generic-password -U -s ${KEYCHAIN_SERVICE} -a ANTHROPIC_API_KEY -l "FrostCode API key" -w "${key}"\n`,
    stdio: ['pipe', 'ignore', 'inherit'],
  });
  console.log(`Saved ANTHROPIC_API_KEY to the login Keychain (service "${KEYCHAIN_SERVICE}").`);
}
if (!existsSync(electronApp)) throw new Error(`Electron is not installed. Run \`npm install\` in ${root}.`);
if (!existsSync(join(root, 'dist/gui/main.js'))) throw new Error(`FrostCode is not built. Run \`npm run build\` in ${root}.`);

// Only ever replace our own bundle.
if (existsSync(app)) {
  let id = '';
  try {
    id = buddy('Print :CFBundleIdentifier');
  } catch {
    /* unreadable plist */
  }
  if (id !== BUNDLE_ID) throw new Error(`${app} exists and is not FrostCode (${id || 'unknown bundle'}); move it away first.`);
  rmSync(app, { recursive: true, force: true });
}

cpSync(electronApp, app, { recursive: true, verbatimSymlinks: true });
const set = (key, value) => {
  try {
    buddy(`Set :${key} ${value}`);
  } catch {
    buddy(`Add :${key} string ${value}`);
  }
};
set('CFBundleName', 'FrostCode');
set('CFBundleDisplayName', 'FrostCode');
set('CFBundleIdentifier', BUNDLE_ID);
set('CFBundleIconFile', 'FrostCode.icns');
cpSync(join(root, 'assets/FrostCode.icns'), join(app, 'Contents/Resources/FrostCode.icns'));

const appDir = join(app, 'Contents/Resources/app');
mkdirSync(appDir, { recursive: true });
writeFileSync(join(appDir, 'package.json'), JSON.stringify({ name: 'frostcode', productName: 'FrostCode', main: 'index.cjs', private: true }, null, 2));
writeFileSync(
  join(appDir, 'index.cjs'),
  `// Generated by scripts/install-app.mjs. Opened from Finder, an app gets launchd's bare environment:
// take PATH (and the API key, if launchd lacks it) from the login shell, then start the GUI.
const { execFileSync } = require('node:child_process');
const { existsSync } = require('node:fs');
const { homedir } = require('node:os');
const { pathToFileURL } = require('node:url');
const { app, dialog } = require('electron');

const ROOT = ${JSON.stringify(root)};
const main = ROOT + '/dist/gui/main.js';

function loginShellEnv() {
  const mark = '__FROSTCODE_ENV__';
  try {
    const out = execFileSync(process.env.SHELL || '/bin/bash', ['-lc', \`printf '\${mark}%s\\\\0%s' "$PATH" "$ANTHROPIC_API_KEY"\`], {
      encoding: 'utf8',
      timeout: 15000,
      stdio: ['ignore', 'pipe', 'ignore'],
    });
    const [path, key] = out.slice(out.lastIndexOf(mark) + mark.length).split('\\0');
    return { path, key };
  } catch {
    return {};
  }
}

const shell = loginShellEnv();
if (shell.path) process.env.PATH = [...new Set([...shell.path.split(':'), ...(process.env.PATH || '').split(':')])].filter(Boolean).join(':');
// The key: the environment, else the Keychain (install-app.mjs --save-key), launchd, the login shell.
const read = (cmd, args) => {
  try {
    return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return '';
  }
};
process.env.ANTHROPIC_API_KEY ||=
  read('/usr/bin/security', ['find-generic-password', '-s', ${JSON.stringify(KEYCHAIN_SERVICE)}, '-a', 'ANTHROPIC_API_KEY', '-w']) ||
  read('/bin/launchctl', ['getenv', 'ANTHROPIC_API_KEY']) ||
  shell.key ||
  '';
if (!process.env.ANTHROPIC_API_KEY) delete process.env.ANTHROPIC_API_KEY;
process.env.FROSTCODE_GUI_DEFAULT_CWD ||= homedir();
delete process.env.ELECTRON_RUN_AS_NODE;

if (!existsSync(main)) {
  app.whenReady().then(() => {
    dialog.showErrorBox('FrostCode', 'FrostCode is not built at ' + ROOT + '.\\nRun \`npm run build\` there, then open the app again.');
    app.quit();
  });
} else {
  import(pathToFileURL(main).href).catch((e) => {
    app.whenReady().then(() => {
      dialog.showErrorBox('FrostCode', 'Could not start: ' + (e && e.message));
      app.quit();
    });
  });
}
`,
);

// Renaming the bundle invalidates Electron's signature; re-sign ad hoc so macOS will launch it.
execFileSync('/usr/bin/codesign', ['--force', '--deep', '--sign', '-', app], { stdio: 'ignore' });
execFileSync('/usr/bin/touch', [app]); // refresh Finder / Launchpad's icon cache
console.log(`Installed ${app} (loads ${root}/dist). Open it from Applications, Launchpad or Spotlight.`);
